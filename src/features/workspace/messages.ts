export type WorkspaceText = (key: keyof typeof copy) => string;
export function workspaceText(language: Language): WorkspaceText {
  return (key) => copy[key][language === 'en' ? 1 : 0];
}

/** 已知错误翻译；未映射的可识别后端代码仍展示，不能伪装成功或泄露原始异常路径。 */
export function detailText(code: string, language: Language): string {
  const entry = Object.entries(copy).find(([key]) => key === code);
  return entry ? entry[1][language === 'en' ? 1 : 0] : code;
}
